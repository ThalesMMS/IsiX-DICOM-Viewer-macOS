def build_and_run(label, pasted, extra, work):
    work.mkdir(parents=True)
    (work / 'standins.swift').write_text(STANDINS + extra)
    (work / 'import.swift').write_text('import AppKit\nimport CoreData\nimport IsiXDatabase\nimport IsiXDICOMFile\nimport IsiXPreferences\n' + pasted)
    (work / 'main.swift').write_text(DRIVER)
    modules = work.parent / 'modules'
    flags = []
    for name in ('IsiXDatabase', 'IsiXDICOMFile'):
        for flag in isix_modules.module_flags(name, modules):
            if flag.startswith('-l') and flag in flags:
                continue
            flags.append(flag)
    built = subprocess.run(['xcrun', 'swiftc', '-swift-version', '5', '-suppress-warnings', *flags,
                            str(work / 'standins.swift'), str(work / 'import.swift'), str(work / 'main.swift'),
                            '-o', str(work / 'probe')], capture_output=True, text=True, timeout=600)
    if built.returncode:
        failures.append('%s does not compile with the stand-ins:\n%s' % (label, built.stderr[-4000:]))
        return None
    data = work / 'data'
    data.mkdir()
    ran = subprocess.run([str(work / 'probe'), str(data)], capture_output=True, text=True, timeout=120)
    if ran.returncode:
        failures.append('%s did not run: %s' % (label, ran.stderr[:2500]))
        return None
    return ran.stdout.replace(str(data), '<data>').splitlines()


