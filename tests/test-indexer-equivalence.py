def member(source, signature):
    at = source.index(signature)
    # Back to the start of the line and its doc comment.
    line = source.rfind('\n', 0, at) + 1
    while True:
        previous = source.rfind('\n', 0, line - 1) + 1
        if line == 0 or not source[previous:line].strip().startswith('///') and not source[previous:line].strip().startswith('//'):
            break
        line = previous
    opening = source.index('{', at)
    depth = 0
    for index in range(opening, len(source)):
        depth += {'{': 1, '}': -1}.get(source[index], 0)
        if depth == 0:
            return source[line:index + 1]
    raise ValueError(signature)


def without(source, signatures):
    for signature in signatures:
        source = source.replace(member(source, signature), '')
    return source


