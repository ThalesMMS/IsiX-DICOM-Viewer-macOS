"""The indexer, a type of its own, makes the rows the import of DicomDatabase made.

DicomFileIndexer took over -addFilesDescribedInDictionaries: and what it calls
(the study, the series and the images of each described file, the comments,
the albums, the reports and what an import tells) from the category of
DicomDatabase in DicomDatabase+Import.swift, and the decisions it can make on
values (the patient of a study, the album marker, the modality and the date a
study takes, a name that says nothing) went to IsiXDatabase's ImportMatching.

This compiles the import of the revision before the move, read from git, and the
indexer of the checkout, each with the same stand-ins: a Core Data model of the
attributes the import writes, over an in-memory store, a database that gives
its folders, its context, its writer gate and its albums, and doubles of what
else the import reaches (the report extraction, the notifications, the
autorouting, the feedback and the disposal). IsiXDatabase and IsiXDICOMFile are
the real ones. One driver seeds a database with rows the import must meet and
imports three batches of described files with edge cases:

- the patient UID of a study in another case, a file without one, and one of
  another patient under the same Study Instance UID;
- a study whose only series is the "No Autodeletion" marker the albums file
  leaves, in an album;
- a study whose series Reparse split (RP-1, RP-2) and a file of the original
  series;
- studies known by an SR and by secondary captures, which take a true modality;
- an earlier and a later date, the undefined date, an unnamed study;
- files that name an album, or one that does not exist;
- multi-frame files with and without the numbers of their frames;
- a report that is extracted and one whose extraction fails, an ROI SR;
- a file read again in the database folder and a copy of it, and a batch read
  again (rereadExistingItems) with a PDF whose physicians are empty;
- a batch generated by the application and imported in place;
- an entry that is not a dictionary;
- two batches of the same files of one study in different orders, one that
  starts with a file without a date and one that starts with the latest date.

Each build prints every row of Study, Series, Image and Album, with the dates of
arrival reduced to whether they are today, the identifiers each batch returned,
the notifications, the alerts and notices, the autorouting and the files left in
the data folder. The two outputs must be the same, line by line.

One change since the move is meant: a file of the same study and patient as the
file before it, which takes the study from the cursor without findStudy, now
also gives the study its date by the rule of findStudy (the earliest real date
wins). Before, only the first file of a run of the same study did, so the date
depended on the order of the files. The import of the revision before is
compiled with that one rule added to its cursor, and the two orders must end
with the same date, the earliest real one, in the checkout's rows.
"""
