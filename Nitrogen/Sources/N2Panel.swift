import Cocoa

/// A panel whose content view is an `N2View`, and which becomes key only when
/// told to.
///
/// Implemented in Swift since #709: the Objective-C name, the selectors and
/// `<Horos/N2Panel.h>` are those of the former class, deprecated as it was.
@available(*, deprecated)
@objc(N2Panel)
public final class N2Panel: NSPanel {
    private var _canBecomeKeyWindow = false

    /// Read-write, and NO until set, as the synthesized property of the former class.
    public override var canBecomeKey: Bool {
        @objc(canBecomeKeyWindow) get { _canBecomeKeyWindow }
        @objc(setCanBecomeKeyWindow:) set { _canBecomeKeyWindow = newValue }
    }

    public override init(contentRect: NSRect, styleMask style: NSWindow.StyleMask, backing backingStoreType: NSWindow.BackingStoreType, defer flag: Bool) {
        super.init(contentRect: contentRect, styleMask: style, backing: backingStoreType, defer: flag)
        contentView = N2View(frame: contentView?.frame ?? NSZeroRect)
    }
}
